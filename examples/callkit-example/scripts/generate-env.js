#!/usr/bin/env node

const path = require('node:path');
const fs = require('node:fs');

const { current_dir, current_package, color_log } = require('./utils');

const out_file = path.join(current_dir, 'src', 'env.ts');
color_log.success(
  `📝 Generate the ${current_package.name}@${current_package.version} env file: ${out_file}`
);
const content = `// This file is automatically generated. The user needs to manually fill in the necessary parameters.\n
export const test = false;
export const appKey = '';
export const appId = '';
export const id = '';
export const ps = '';
export const accountType = ''; // agora | easemob | shengwang // only with callkit
export const agoraAppId = '';
export const fcmSenderId = '';
export const appServerDomain = '';
export const reactStrictMode = false;
`;
if (fs.existsSync(out_file) === false) {
  fs.writeFileSync(out_file, content, 'utf-8');
}
